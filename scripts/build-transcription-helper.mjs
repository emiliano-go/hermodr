import { copyFileSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";

const root = fileURLToPath(new URL("../", import.meta.url));
const profile = process.argv.includes("--release") ? "release" : "debug";
const targetIndex = process.argv.indexOf("--target");
const target = targetIndex >= 0 ? process.argv[targetIndex + 1] : process.env.TAURI_ENV_TARGET_TRIPLE;
const rust = spawnSync("rustc", ["-vV"], { encoding: "utf8" });
if (rust.status !== 0) throw new Error("Cannot determine Rust target");
const triple = target ?? rust.stdout.match(/^host: (.+)$/m)?.[1]?.trim();
if (!triple || !/^[a-z0-9_]+(?:-[a-z0-9_]+)+$/.test(triple)) throw new Error("Invalid target triple");
const args = ["build", "--manifest-path", join(root, "plugins", "credential-helper", "Cargo.toml"), "--locked"];
if (profile === "release") args.push("--release");
if (target) args.push("--target", target);
const build = spawnSync("cargo", args, { cwd: root, stdio: "inherit" });
if (build.status !== 0) process.exit(build.status ?? 1);
const targetDirectory = process.env.CARGO_TARGET_DIR ? resolve(root, process.env.CARGO_TARGET_DIR) : join(root, "plugins", "credential-helper", "target");
const executable = `postal-transcription-key${triple.includes("windows") ? ".exe" : ""}`;
const source = join(targetDirectory, ...(target ? [target] : []), profile, executable);
const staged = join(root, "src-tauri", "binaries", `postal-transcription-key-${triple}${triple.includes("windows") ? ".exe" : ""}`);
mkdirSync(dirname(staged), { recursive: true });
copyFileSync(source, staged);
const appTarget = process.env.CARGO_TARGET_DIR ? resolve(root, process.env.CARGO_TARGET_DIR) : join(root, "src-tauri", "target");
const sibling = join(appTarget, profile, executable);
mkdirSync(dirname(sibling), { recursive: true });
if (source !== sibling) copyFileSync(source, sibling);
console.log(`Staged native credential helper for ${triple}. Helper was not executed.`);
